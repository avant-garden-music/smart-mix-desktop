#[cfg(test)]
mod tests {
    /// Las claves nuevas FALLAN EN SILENCIO (cascada es→en→clave devuelve la
    /// propia clave): este test obliga a que la inserción exista en AMBOS
    /// idiomas antes de que el tooltip llegue a producción.
    #[test]
    fn studio_sort_hint_exists_in_both_languages() {
        assert_eq!(super::t("es", "studio.sort_hint"), "Clic para ordenar");
        assert_eq!(super::t("en", "studio.sort_hint"), "Click to sort");
        // y para cualquier otro idioma cae al bloque en
        assert_eq!(super::t("fr", "studio.sort_hint"), "Click to sort");
    }

    /// analyze-live: el status bar rotativo muestra la pista en análisis con
    /// esta clave — si falta en algún idioma se pintaría la clave cruda.
    #[test]
    fn studio_analyzing_now_exists_in_both_languages() {
        assert_eq!(
            super::t("es", "studio.analyzing_now"),
            "Analizando: {track}"
        );
        assert_eq!(super::t("en", "studio.analyzing_now"), "Analyzing: {track}");
        assert_eq!(super::t("fr", "studio.analyzing_now"), "Analyzing: {track}");
    }

    /// fix table-rb: el header de Duración va COMPLETO, sin abreviar (antes
    /// "Dur."/"Len."). El mínimo de la columna de la tabla se mide contra
    /// estas palabras — abreviar de vuelta rompería el contrato del ancho.
    #[test]
    fn studio_duration_header_is_the_full_word_in_both_languages() {
        assert_eq!(super::t("es", "studio.duration"), "Duración");
        assert_eq!(super::t("en", "studio.duration"), "Duration");
        // otros idiomas caen al bloque en
        assert_eq!(super::t("fr", "studio.duration"), "Duration");
    }
}
